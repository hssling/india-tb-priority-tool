    loo = read_csv(root, "outputs/leave_one_out.csv")

    def loo_range(an: str) -> tuple[str, str]:
        """(the range of rho, the units whose omission gives each end)."""
        lo = [r for r in loo if r["analysis"] == an and r["extreme"] == "min"]
        hi = [r for r in loo if r["analysis"] == an and r["extreme"] == "max"]
        lo_names = and_list(sorted(r["omitted"] for r in lo)).replace(" and ", " or ")
        hi_names = and_list(sorted(r["omitted"] for r in hi)).replace(" and ", " or ")
        return (rng(rho(lo[0]["value"]), rho(hi[0]["value"])),
                f"lowest without {lo_names}; highest without {hi_names}")

    h1, h2, h3 = hl["H1"], hl["H2"], hl["H3"]
    ov = {s: hl[f"H1 top-5 overlap {s}"]["value"] for s in ("S3", "S4", "S6")}
    tot = hl["H1 top-5 overlap"]
    gap = hl["H1 rate-gap rho (descriptive)"]
    sig = hl["H2 signed shortfall per 100,000 (descriptive)"]
    rows = [
        ["H1", "Temporal stability: harm averted, pre-period against 2023 (within-step ranks; S3, S4, S6)",
         f"{rho(h1['value'])} ({rng(rho(h1['lo']), rho(h1['hi']))})", f"{count(h1['n'])} pairs",
         f"{count(h1['n_agree'])} of {count(h1['n_grid'])}", h1["label"]],
        ["H2", "External association: 2023 S1 harm averted per 100,000 against survey prevalence",
         f"{rho(h2['value'])} ({rng(rho(h2['lo']), rho(h2['hi']))})", f"{count(h2['n'])} survey units",
         f"{count(h2['n_agree'])} of {count(h2['n_grid'])}", h2["label"]],
        ["H3", "Concentration: share of 2023 harm averted (S2 to S5) in each step's top five",
         pct(h3["value"]), f"{count(h3['n'])} steps", DASH, "none (descriptive)"],
        ["H1, rate gaps", "As H1, on rate gaps (unit size removed)", rho(gap["value"]),
         f"{count(gap['n'])} pairs", DASH, "none (descriptive)"],
        ["H1, top-five overlap", "Units in the top five of both the pre-period and 2023",
         f"{count(tot['value'])} of {count(tot['n'])} places (S3 {count(ov['S3'])}, S4 {count(ov['S4'])}, "
         f"S6 {count(ov['S6'])})", f"{count(len(ov))} steps", DASH, "none (descriptive)"],
        ["H1, leave-one-out", f"Each unit left out in turn ({loo_range('H1')[1]})", loo_range("H1")[0],
         f"{count(len([r for r in loo if r['analysis'] == 'H1']))} units", DASH, "none (descriptive)"],
        ["H2, signed shortfall", "As H2, with target minus notified per 100,000",
         f"{rho(sig['value'])} ({rng(rho(sig['lo']), rho(sig['hi']))})", f"{count(sig['n'])} survey units",
         DASH, "none (descriptive)"],
        ["H2, leave-one-out", f"Each survey unit left out in turn ({loo_range('H2')[1]})", loo_range("H2")[0],
         f"{count(len([r for r in loo if r['analysis'] == 'H2']))} survey units", DASH,
         "none (descriptive)"],
    ]
    for s in ("S2", "S3", "S4", "S5"):
        r = hl[f"H3 share {s}"]
        rows.append([f"H3, {s}", f"Top five: {r['note'].removeprefix('top 5: ')}",
                     pct(r["value"]), f"{count(r['n'])} units", DASH, "none (descriptive)"])
    notes = [
        "Main specification: benchmark at the better quartile of units, empirical-Bayes shrinkage on. "
        "Intervals are 95% intervals: H1, bootstrap over units (10,000 draws); H2 and the signed "
        "shortfall, Fisher-z with Fieller's variance. A label is given to H1 and H2 only: "
        "\"supported\" if the main interval excludes 0 and at least 80% of the 12 specification-grid "
        "entries agree in sign with the main estimate, otherwise \"not established\". H1 pre-period: "
        "data years 2018, 2019 and 2021 (S4: 2019 and 2021). Survey: the national tuberculosis "
        "prevalence survey of 2019 to 2021. Top-five places tied at the fifth place are broken "
        "alphabetically. Pairs: unit-step pairs. Survey units: the survey's State and State-group reporting "
        "units. Grid entries agreeing: entries of the 12-entry specification grid with the same sign as the main "
        "estimate. " + DASH + ", not applicable.",
    ]
    return Table("Table 1", "Headline estimates, their intervals and their pre-specified labels",
                 ["Estimate", "What it measures", "Value (95% interval)", "n", "Grid entries agreeing",
                  "Label"], rows, set(), notes)


