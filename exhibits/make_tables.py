def table2(root: Path) -> Table:
    pr = priority_rows(root)
    rows = []
    for s in STEPS:
        rs = [r for r in pr if r["step"] == s]
        cells = []
        for t in TIERS[:4]:
            names = sorted(r["unit"] + (" (rising)" if r["rising"] == "True" and t != "watch: rising" else "")
                           for r in rs if r["tier"] == t)
            cells.append(", ".join(names) if names else DASH)
