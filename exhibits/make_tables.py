def tables4(root: Path) -> Table:
    tr = read_csv(root, "outputs/state_trend.csv")
    rows = []
    for basis, s in [("main", s) for s in STEPS] + [("s6_2022_registered", "S6")]:
        rs = [r for r in tr if r["basis"] == basis and r["step"] == s]
        status = Counter(r["trend_status"] for r in rs)
        est = [r for r in rs if r["trend_status"] == "estimated"]
        allyears = sorted({y for r in est for y in r["years"].split(";")})
        short = sum(r["years"].split(";") != allyears for r in est)
        years = ", ".join(allyears) + (f" ({count(short)} units without a year)" if short else "")
        phis = sorted({r["phi"] for r in est})
        name = step_label(s) + (" (registered S6 2022 basis)" if basis != "main" else "")
        if not est:
            rows.append([name, DASH, next(iter(status)), DASH, DASH, DASH, DASH])
            continue
        rows.append([name, years,
                     f"{count(len(est))} of {count(len(rs))}", num(phis[0], 1),
                     count(sum(r["rising"] == "True" for r in est)),
                     count(sum(r["sens_rising"] == "True" for r in est)),
                     count(sum(r["rising_differs"] == "True" for r in est))])
    notes = ["Main model: weighted least squares of the empirical logit of the loss rate (S1: log achievement) on "
             "year, with a 2021 year indicator where a year before 2021 exists (S3, S4, S6); standard errors "
             "scaled by φ, the step's pooled Pearson χ² per degree of freedom (at least 1). "
             "Sensitivity: the same model without the indicator (S1: with it). Rising: the slope's 95% interval "
             "lies wholly on the worsening side. S2 changes definition in 2022 and S5 cohorts are not comparable "
             "across editions, so neither has a trend."]
    return Table("Table S3", "Trend models by step: years, units estimated, overdispersion and rising flags",
                 ["Step", "Data years", "Units estimated / status", "φ", "Rising (main)", "Rising (sensitivity)",
                  "Flags differing"], rows, set(), notes)


