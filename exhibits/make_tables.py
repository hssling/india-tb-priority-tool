def tables9(root: Path) -> Table:
    na = read_csv(root, "outputs/na_cells.csv")
    c: Counter = Counter()
    for r in na:
        flags = r["reason"].split(";")
        if flags[0].startswith("NA:"):
            kind = REASON[flags[0]]
        elif any(f.startswith("member_missing") for f in flags):
            kind = "merged unit with a member missing"
        elif any(f.startswith("denominator_") for f in flags):
            kind = REASON[next(f for f in flags if f.startswith("denominator_"))]
        elif any(f.startswith("cohort_") for f in flags):
            kind = "treatment cohort named"
        else:
            kind = "merged unit"
        c[(r["panel"], r["na"], kind)] += 1
    names = {"state_panel": "Main panel", "state_panel_s6_2022_registered": "Registered S6 2022 panel"}
    rows = [[names[p], "not used (NA)" if n == "True" else "used, flagged", k, count(v)]
            for (p, n, k), v in sorted(c.items(), key=lambda kv: (kv[0][0], kv[0][1], -kv[1], kv[0][2]))]
    notes = ["Every NA or flagged cell of the two State panels, each counted once under its main reason (in "
             "this order: NA, a merged unit with a member missing, the denominator, the treatment cohort, a "
             "merged unit). No value is imputed. A merged unit sums a small Union Territory into a neighbouring "
             "unit. The main S6 2022 denominator is a deviation from the registered plan, decided before any "
             "estimate (Table S8)."]
    return Table("Table S9", "NA and flagged cells of the State panels", ["Panel", "Status", "Main reason", "Cells"],
                 rows, set(), notes)


