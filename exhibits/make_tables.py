class Table(NamedTuple):
    label: str            # "Table 1", "Table S3"
    title: str
    header: list[str]
    rows: list[list[str]]  # a spanning block label is [label, "", ...] and printed bold
    spans: set[int]        # indices of rows that are block labels
    notes: list[str]

    @property
    def csv_name(self) -> str:
        """Table 1 -> table1.csv; Table S3 -> tables3.csv."""
        return "table" + self.label.split()[1].lower() + ".csv"


def step_label(s: str) -> str:
    return f"{s} {STEP_NAMES[s]}"


