def pages(ps: set[str]) -> str:
    """'213', '213;214', '214' -> '213-214' (each page once, as a range when consecutive)."""
    nums = sorted({int(p) for x in ps for p in x.split(";")})
    out, start, prev = [], nums[0], nums[0]
    for n in nums[1:] + [None]:
        if n is not None and n == prev + 1:
            prev = n
            continue
        out.append(str(start) if start == prev else f"{start}–{prev}")
        if n is not None:
            start = prev = n
    return ", ".join(out)


EDITION = {"India-TB-Report-2019.pdf": "India TB Report 2019", "ITR2020.pdf": "India TB Report 2020",
           "TBAnnaulReport2022.pdf": "TB Annual Report 2022", "ITR2023.pdf": "India TB Report 2023",
           "ITR2024.pdf": "India TB Report 2024"}


def tables1(root: Path) -> Table:
    panel = read_csv(root, "data/extracted/state_panel.csv")
    groups: dict[tuple, dict] = {}
    for r in panel:
        k = (r["step"], r["year"])
        g = groups.setdefault(k, {"files": set(), "tables": set(), "pages": set(), "units": set(), "cohort": set()})
        g["files"].add(r["source_file"].rsplit("/", 1)[-1])
        g["tables"].add(r["table_id"])
        g["pages"].add(r["pdf_page"])
        g["units"].add(r["unit"])
        g["cohort"] |= {f.removeprefix("cohort_") for f in r["flag"].split(";") if f.startswith("cohort_")}
    rows, spans = [], set()
    for s in STEPS:
        spans.add(len(rows))
        rows.append([f"**{step_label(s)}**", "", "", "", ""])
        for (st, y), g in sorted(groups.items()):
            if st != s:
                continue
            (f,) = g["files"]
            (t,) = g["tables"]
            tables = t.replace(";", "; ").replace("Annexure", "Annexure")
            rows.append([y, EDITION[f], tables, pages(g["pages"]), ", ".join(sorted(g["cohort"])) or DASH])
    notes = ["Pages are pages of the PDF files. A cohort is the treatment cohort reported for the data year "
             "(S3, S4: DS-TB patients notified in that year; S5: MDR/RR-TB patients initiated on treatment). "
             "Data year 2020 is not used (its report has no text layer). For S6 in data year 2022 the denominator "
             "is the sum of Annexure 1.6 (notified by sex), the basis of the numerator's own table; the registered "
             "Annexure 1.2 basis is reported as a sensitivity (Table S8). " + DASH + ", not applicable."]
    return Table("Table S1", "Source table of each step and data year (State panel; 33 units in every year)",
                 ["Data year", "Report", "Table", "PDF pages", "Cohort"], rows, spans, notes)


